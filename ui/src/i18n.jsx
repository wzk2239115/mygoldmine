const LanguageContext = createContext({
  language: 'zh',
  t: (key) => key,
  setLanguage: () => {}
});

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    const injected = typeof window !== 'undefined' ? window.__MYGOLDMINE_LANGUAGE__ : null;
    if (injected === 'en' || injected === 'zh') return injected;
    const saved = localStorage.getItem('vul-ai-language');
    return saved === 'en' ? 'en' : 'zh';
  });

  useEffect(() => {
    let active = true;
    fetch('/api/language')
      .then((response) => (response.ok ? response.json() : null))
      .then((payload) => {
        if (active && (payload?.language === 'en' || payload?.language === 'zh')) {
          setLanguageState(payload.language);
          localStorage.setItem('vul-ai-language', payload.language);
        }
      })
      .catch(() => {});
    return () => {
      active = false;
    };
  }, []);

  const setLanguage = useCallback(async (next) => {
    const value = next === 'en' ? 'en' : 'zh';
    setLanguageState(value);
    localStorage.setItem('vul-ai-language', value);
    try {
      await fetch('/api/language', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ language: value })
      });
    } catch {
      // keep the local choice if the server is temporarily unavailable
    }
  }, []);

  const t = useCallback(
    (key) => DICT[language]?.[key] || DICT.zh[key] || key,
    [language]
  );

  const value = useMemo(() => ({ language, t, setLanguage }), [language, t, setLanguage]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  return useContext(LanguageContext);
}
